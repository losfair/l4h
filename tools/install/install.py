ESP_TYPE = "c12a7328-f81f-11d2-ba4b-00a0c93ec93b"
EFI_GLOBAL = "8be4df61-93ca-11d2-aa0d-00e098032b8c"
LOADER = r"\EFI\L4H\l4h.efi"
STATE = Path("/var/lib/l4h/install.json")
BIOS_PACKAGE = "l4h-bios-x86_64"
BIOS_DIR = Path("/boot/l4h")
GRUB_ENTRY = "l4h"
GENERATED = "# Generated by the L4H Linux installer.\n"
KERNEL_VARIANTS = ("generic", "xapic-nopcid", "skim-xapic-nopcid")
PCID_FLAGS = {"pcid", "invpcid", "x2apic"}
CPU_FLAGS = set("lm nx syscall sse sse2 apic msr pae pse pdpe1gb fsgsbase xsave xsaveopt avx constant_tsc".split())
DOM0_MIN_MB = 512
DOM0_MAX_MB = 61440
HOST_RESERVE_MB = 256


class Incompatible(RuntimeError):
    pass


def need(condition, message):
    if not condition:
        raise Incompatible(message)


def run(*args):
    result = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            text=True, env=dict(os.environ, LC_ALL="C"))
    need(result.returncode == 0, "{}: {}".format(" ".join(map(str, args)), result.stderr.strip()))
    return result.stdout.strip()


def digest(path):
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def boot_state(text):
    def field(name):
        match = re.search(r"^" + name + r":\s*([0-9A-Fa-f,]+)$", text, re.M)
        return match[1].upper() if match else None
    matches = list(re.finditer(r"^Boot([0-9A-Fa-f]{4})(\*?)\s+(.+)$", text, re.M))
    entries = {m[1].upper(): m[3] for m in matches}
    order = field("BootOrder")
    need(order and re.fullmatch(r"[0-9A-F]{4}(,[0-9A-F]{4})*", order),
         "firmware has no readable BootOrder; configure a native Linux boot entry first")
    return {"order": order, "next": field("BootNext"), "current": field("BootCurrent"),
            "entries": entries, "active": sorted(m[1].upper() for m in matches if m[2])}


def l4h_entry(boot, plan=None, preferred=None):
    if plan is not None:
        # Entry numbers and duplicate labels are not identities. Match this
        # deployment's ESP and loader, preferring its recorded entry or order.
        order = [preferred, *boot["order"].split(","), *sorted(boot["entries"])]
        return next((entry for entry in order if owns_entry(boot, entry, plan)), None)
    entries = [num for num, text in boot["entries"].items()
               if text.split()[0] == "L4H" and LOADER.lower() in text.lower()]
    need(len(entries) <= 1, "multiple L4H boot entries; resolve them with efibootmgr first")
    return entries[0] if entries else None


def owns_entry(boot, entry, plan):
    text = boot["entries"].get(entry, "")
    disk_path = "HD({esp_part},GPT,{esp_partuuid},".format(**plan).lower()
    loader = re.search(re.escape(LOADER) + r"(?:\)|\s|$)", text, re.I)
    return (bool(text) and text.split()[0] == "L4H" and loader is not None
            and disk_path in text.lower())


def grub_env(text):
    """`grub-editenv FILE list` output as a dict."""
    return dict(line.split("=", 1) for line in text.splitlines() if "=" in line)


def config_value(text, key):
    values = re.findall(r"^[ \t]*" + re.escape(key) + r"=(.*)$", text, re.M)
    need(len(values) == 1, "installed l4h.conf needs exactly one " + key)
    words = shlex.split(values[0], comments=True)
    need(len(words) == 1, "cannot read " + key + " from installed l4h.conf")
    return words[0]


def config_replace(text, key, value):
    pattern = r"^[ \t]*" + re.escape(key) + r"=[^\n]*$"
    need(len(re.findall(pattern, text, re.M)) <= 1, "duplicate " + key + " in installed l4h.conf")
    replaced, count = re.subn(pattern, key + "=" + str(value), text, flags=re.M)
    return replaced if count else text + ("" if text.endswith("\n") else "\n") + f"{key}={value}\n"


def memory_size(total, requested):
    need(total >= DOM0_MIN_MB + HOST_RESERVE_MB,
         f"need at least {DOM0_MIN_MB + HOST_RESERVE_MB} MiB usable RAM "
         f"({DOM0_MIN_MB} MiB for dom0 and {HOST_RESERVE_MB} MiB for L4H); found {total} MiB")
    # vmmgr allocates guest RAM in 2 MiB blocks.
    maximum = min((total - HOST_RESERVE_MB) // 2 * 2, DOM0_MAX_MB)
    memory = requested if requested is not None else max(DOM0_MIN_MB, min(total // 2, 8192))
    need(DOM0_MIN_MB <= memory <= maximum,
         f"dom0 RAM must be {DOM0_MIN_MB}..{maximum} MiB on this machine "
         f"({total} MiB usable RAM, reserving {HOST_RESERVE_MB} MiB for L4H)")
    return memory


def grub_entry(plan, default):
    """custom.cfg: the L4H menu entry, which runs tools/mkbios.sh's grub.cfg.

    grub.cfg's 00_header sets boot_once when it consumes a one-time next_entry,
    which must then win over a permanent L4H default.
    """
    text = (GENERATED +
            "menuentry 'L4H' --id {entry} {{\n"
            "    insmod part_gpt\n    insmod part_msdos\n    insmod {fs}\n"
            "    search --no-floppy --fs-uuid --set=root {uuid}\n"
            "    set l4h=($root){dir}\n"
            "    source \"$l4h/bios/grub.cfg\"\n"
            "}}\n").format(entry=GRUB_ENTRY, fs="xfs" if plan["boot_fstype"] == "xfs" else "ext2",
                           uuid=plan["boot_uuid"], dir=plan["grub_dir"])
    if default:
        text += 'if [ -z "$boot_once" ]; then set default={}; fi\n'.format(GRUB_ENTRY)
    return text


class Preflight:
    def __init__(self, args, root=Path("/"), command=run):
        self.args, self.root, self.run = args, root, command
        self.variants = {}

    def path(self, path):
        return self.root / str(path).lstrip("/")

    def read(self, path):
        return self.path(path).read_text().strip()

    def mounts(self, *args):
        return json.loads(self.run("findmnt", "--json", "--list", *args,
                                   "--output", "SOURCE,TARGET,FSTYPE,OPTIONS,MAJ:MIN"))["filesystems"]

    def mount(self, path):
        entries = self.mounts("--target", str(path))
        need(len(entries) == 1, "cannot identify mount for " + str(path))
        return entries[0]

    def firmware(self):
        return "uefi" if self.path("/sys/firmware/efi").exists() else "bios"

    def cpu_variant(self, requested):
        processors = []
        for block in self.read("/proc/cpuinfo").split("\n\n"):
            fields = dict(line.split(":", 1) for line in block.splitlines() if ":" in line)
            fields = {key.strip(): value.strip() for key, value in fields.items()}
            if "processor" in fields:
                processors.append(fields)
        need(processors, "cannot read CPU features")
        flags = set.intersection(*(set(cpu.get("flags", "").split()) for cpu in processors))
        missing = CPU_FLAGS - flags
        if self.args.assume_stable_tsc:
            missing.discard("constant_tsc")
        need(not missing, "CPU is missing required features: " + " ".join(sorted(missing)))
        if "constant_tsc" not in flags:
            print("l4h: warning: constant_tsc is not advertised; --assume-stable-tsc "
                  "assumes a stable TSC without verifying it", file=sys.stderr)
        need(all(cpu.get("vendor_id") in ("GenuineIntel", "AuthenticAMD") for cpu in processors),
             "only Intel and AMD CPUs are supported by this installer")
        # Linux's PTI protects Linux only. Affected or unknown CPUs need
        # L4H's own isolation. Without ARCH_CAPABILITIES an Intel CPU also
        # fails the non-SKIM kernel's RDCL_NO boot check (patch 0024).
        try:
            meltdown = self.read("/sys/devices/system/cpu/vulnerabilities/meltdown")
        except FileNotFoundError:
            meltdown = "Unknown"
        skim = (meltdown != "Not affected" or
                any(cpu["vendor_id"] == "GenuineIntel" for cpu in processors) and
                "arch_capabilities" not in flags)
        variant = requested or ("skim-xapic-nopcid" if skim else
                                "generic" if PCID_FLAGS <= flags else "xapic-nopcid")
        need(variant == "skim-xapic-nopcid" or not skim,
             "this CPU requires the skim-xapic-nopcid variant for Meltdown isolation")
        if variant == "generic":
            need(PCID_FLAGS <= flags, "generic requires PCID, INVPCID and x2APIC")
        need(all(int(cpu.get("apicid", "256")) < 256 for cpu in processors),
             "APIC IDs above 255 are not supported by the shipped interrupt routing")
        return variant, len(processors)

    def hardware(self):
        need(platform.system() == "Linux" and platform.machine() == "x86_64",
             "only x86_64 Linux is supported")
        if self.firmware() == "uefi":
            need(self.read("/sys/firmware/efi/fw_platform_size") == "64", "64-bit UEFI is required")
            variables = self.mount("/sys/firmware/efi/efivars")
            need(variables["fstype"] == "efivarfs" and "rw" in variables["options"].split(","),
                 "efivarfs must be mounted read-write at /sys/firmware/efi/efivars")
            try:
                secure = self.path("/sys/firmware/efi/efivars/SecureBoot-" + EFI_GLOBAL).read_bytes()
            except FileNotFoundError:
                # Non-Secure-Boot-capable firmware (e.g. plain OVMF) has no
                # variable. This is Linux's efi_get_secureboot_mode() rule too.
                secure = b"\0" * 5
            need(len(secure) == 5 and secure[4] == 0,
                 "disable Secure Boot in firmware first; the L4H release is unsigned")
        need(self.path("/sys/firmware/acpi/tables/APIC").is_file(), "ACPI MADT (APIC) is required")
        variant, cpus = self.cpu_variant(self.args.variant)
        total = int(re.search(r"^MemTotal:\s+(\d+)", self.read("/proc/meminfo"), re.M)[1]) // 1024
        memory = memory_size(total, self.args.memory)
        vcpus = self.args.vcpus if self.args.vcpus is not None else min(cpus, 4)
        need(1 <= vcpus <= min(cpus, 64), "dom0 vCPUs must fit the available CPUs (maximum 64)")
        return variant, memory, vcpus

    def pci(self, sys_path):
        path = self.path(sys_path).resolve()
        pci = next((p for p in (path, *path.parents)
                    if re.fullmatch(r"[0-9a-f]{4}:[0-9a-f]{2}:[0-9a-f]{2}\.[0-7]", p.name)), None)
        need(pci is not None, str(sys_path) + ": requires a supported PCI device")
        need(pci.name.startswith("0000:"), "only PCI segment 0000 is supported")
        number = lambda name: int((pci / name).read_text().strip(), 16)
        config = (pci / "config").read_bytes()
        need(len(config) >= 64, "cannot read PCI capabilities for " + pci.name)
        # Walk the conventional capability list, with cycle and bounds checks.
        offset, seen, msix, modern, virtio = config[0x34] & ~3, set(), 0, False, False
        while offset:
            need(0x40 <= offset <= min(len(config) - 4, 0xFC) and offset not in seen,
                 "invalid or unreadable PCI capability list for " + pci.name)
            seen.add(offset)
            if config[offset] == 0x11:
                msix = (int.from_bytes(config[offset + 2:offset + 4], "little") & 0x7FF) + 1
            if config[offset] == 9:
                virtio = True
                modern |= config[offset + 3] == 1
            offset = config[offset + 1] & ~3
        bars = []
        for line in (pci / "resource").read_text().splitlines()[:6]:
            start, end, flags = (int(x, 16) for x in line.split())
            bars.append((end - start + 1 if start else 0, bool(flags & 0x100)))
        need(len(bars) == 6, "cannot read PCI BARs for " + pci.name)
        return dict(bdf=pci.name[5:], vendor=number("vendor"), device=number("device"),
                    cls=number("class"), msix=msix, modern=modern, bars=bars,
                    legacy=not virtio and bars[0][1] and bars[0][0] >= 0x20)

    def disk(self, block):
        if block["type"] == "part":
            block = self.blocks.get(block["pkname"])
        need(block is not None and block["type"] == "disk",
             "only plain disks/partitions are supported (no LVM, dm-crypt, RAID or multipath)")
        name = Path(block["name"]).name
        pci = self.pci("/sys/class/block/" + name)
        vendor, device = pci["vendor"], pci["device"]
        # Modern, or legacy (0.9.5) with only the transitional device ID.
        virtio = vendor == 0x1AF4 and (
            device in (0x1001, 0x1042) and (pci["modern"] or device == 0x1001 and pci["legacy"]) or
            device in (0x1004, 0x1048) and (pci["modern"] or device == 0x1004 and pci["legacy"]))
        nvme = pci["cls"] == 0x010802 and pci["bars"][0][0] >= 0x2000
        need(pci["msix"] and (virtio or nvme), block["name"] +
             ": L4H needs NVMe, virtio-blk or virtio-scsi with MSI-X; SATA/SAS/USB are unsupported")
        if nvme:
            need(self.read("/sys/class/block/" + name + "/nsid") == "1",
                 block["name"] + ": L4H supports only NVMe namespace 1")
        return pci["bdf"]

    def stable_device(self, spec):
        for prefix, key in (("UUID=", "uuid"), ("PARTUUID=", "partuuid"),
                            ("LABEL=", "label"), ("PARTLABEL=", "partlabel"),
                            ("/dev/disk/by-uuid/", "uuid"), ("/dev/disk/by-partuuid/", "partuuid")):
            if spec.startswith(prefix):
                value = spec[len(prefix):]
                matches = [b for b in self.blocks.values() if b.get(key) == value]
                need(len(matches) == 1, "missing or ambiguous device: " + spec)
                return matches[0]
        raise Incompatible("fstab must use UUID/PARTUUID or unique labels for block devices; unstable source: " + spec)

    def storage(self):
        data = json.loads(self.run("lsblk", "--json", "--list", "--paths", "--output",
                                  "NAME,TYPE,PKNAME,FSTYPE,UUID,PARTUUID,LABEL,PARTLABEL,PARTTYPE,PTTYPE,MAJ:MIN"))
        self.blocks = {b["name"]: b for b in data["blockdevices"]}
        root_mount = self.mount("/")
        matches = [b for b in self.blocks.values() if b["maj:min"] == root_mount["maj:min"]]
        need(len(matches) == 1 and root_mount["fstype"] in ("ext4", "xfs"),
             "root must be a plain ext4 or XFS disk/partition")
        root = matches[0]
        need("rw" in root_mount["options"].split(","), "root must be writable")
        root_bdf = self.disk(root)
        need(root.get("uuid") and re.fullmatch(r"[0-9a-fA-F-]+", root["uuid"]), "root needs a filesystem UUID")
        need(sum(b.get("uuid") == root["uuid"] for b in self.blocks.values()) == 1,
             "root filesystem UUID is duplicated")
        for path in ("/usr", "/etc", "/lib/modules", "/sbin/init"):
            mount = self.mount(path)
            need(mount["maj:min"] == root_mount["maj:min"] and mount["target"] == "/",
                 path + " must be on the root filesystem, without a separate or bind mount")
        for path in ("/lib/modules", "/dev", "/proc", "/sys", "/run"):
            need(self.path(path).is_dir(), "missing root directory: " + path)
        need(os.access(self.path("/sbin/init"), os.X_OK), "no executable /sbin/init")
        crypttab = self.path("/etc/crypttab")
        need(not crypttab.exists() or not any(line.strip() and not line.lstrip().startswith("#")
                                             for line in crypttab.read_text().splitlines()),
             "crypttab entries need a custom initramfs; automatic encrypted-volume migration is unsupported")
        fstab = self.mounts("--fstab")
        need(any(m["target"] == "/" for m in fstab), "fstab needs a persistent root entry")
        for mount in fstab:
            spec, kind, target = mount["source"], mount["fstype"], mount["target"]
            if kind in ("proc", "sysfs", "devtmpfs", "tmpfs", "devpts", "cgroup2"):
                continue
            if kind == "swap" and spec.startswith("/") and not spec.startswith("/dev/"):
                need(self.path(spec).is_file() and self.mount(spec)["maj:min"] == root_mount["maj:min"],
                     "swap file must be on root: " + spec)
                continue
            # The guest's ext4 driver also mounts ext2/3, including BIOS /boot.
            need(kind in ("ext2", "ext3", "ext4", "xfs", "vfat", "swap"), "unsupported fstab filesystem: " + kind)
            block = self.stable_device(spec)
            self.disk(block)
            need(block.get("fstype") == kind, "fstab filesystem differs from the disk: " + spec)
            if target == "/":
                need(block["name"] == root["name"], "fstab root differs from the mounted root")
        plan = dict(firmware=self.firmware(), root_uuid=root["uuid"], root_type=root_mount["fstype"],
                    boot_disk=root_bdf)
        plan.update(self.esp() if plan["firmware"] == "uefi" else self.grub())
        return plan

    def esp(self, physical=True, target=None):
        candidates = []
        for mount in self.mounts():
            if mount["fstype"] != "vfat":
                continue
            block = next((b for b in self.blocks.values() if b["maj:min"] == mount["maj:min"]), {})
            if (block.get("parttype") or "").lower() == ESP_TYPE:
                candidates.append((mount, block))
        target = self.args.esp or target
        if target:
            candidates = [(m, b) for m, b in candidates if m["target"] == str(Path(target).resolve())]
        need(len(candidates) == 1, "need one mounted GPT EFI system partition; use --esp to select it")
        esp, partition = candidates[0]
        need("rw" in esp["options"].split(","), "EFI system partition is read-only")
        disk = self.blocks.get(partition["pkname"], {})
        need(partition["type"] == "part" and disk.get("type") == "disk" and disk.get("pttype") == "gpt",
             "ESP must be a partition on a plain GPT disk")
        if physical:
            self.disk(partition)
        partnum = self.read("/sys/class/block/" + Path(partition["name"]).name + "/partition")
        need(partnum.isdigit() and int(partnum) > 0, "cannot determine the ESP partition number")
        partuuid = partition.get("partuuid") or ""
        need(re.fullmatch(r"[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}", partuuid),
             "cannot determine the ESP partition UUID")
        return dict(esp=esp["target"], esp_disk=disk["name"], esp_part=partnum, esp_partuuid=partuuid)

    def grub(self, physical=True):
        # The distribution's BIOS GRUB, whose grub.cfg (grub-mkconfig's) sources
        # custom.cfg and consumes a one-time next_entry before it boots it.
        need(not physical or "BOOT_IMAGE=" in self.read("/proc/cmdline"),
             "BIOS installation needs native Linux booted by GRUB (no BOOT_IMAGE= on the kernel command line)")
        dirs = [d for d in ("/boot/grub", "/boot/grub2") if self.path(d + "/grub.cfg").is_file()]
        need(len(dirs) == 1, "need exactly one of /boot/grub/grub.cfg and /boot/grub2/grub.cfg")
        grubdir = dirs[0]
        text = self.path(grubdir + "/grub.cfg").read_text(errors="replace")
        need("custom.cfg" in text and "next_entry" in text,
             grubdir + "/grub.cfg must come from grub-mkconfig (it needs 00_header and 41_custom)")
        need(self.path(grubdir + "/grubenv").is_file(), "missing GRUB environment block " + grubdir + "/grubenv")
        mount = self.mount(grubdir)
        need(mount["maj:min"] == self.mount(str(BIOS_DIR.parent))["maj:min"],
             grubdir + " must be on the /boot filesystem")
        # GRUB rewrites grubenv in place to consume next_entry; it can on these.
        need(mount["fstype"] in ("ext2", "ext3", "ext4", "xfs"), "/boot must be ext2/3/4 or XFS for BIOS GRUB")
        need("rw" in mount["options"].split(","), "/boot must be mounted read-write")
        matches = [b for b in self.blocks.values() if b["maj:min"] == mount["maj:min"]]
        need(len(matches) == 1 and matches[0].get("uuid"), "cannot identify the /boot filesystem")
        block = matches[0]
        need(block["type"] in ("part", "disk"), "/boot must be a plain disk or partition")
        if physical:
            self.disk(block)
        disk = self.blocks[block["pkname"]] if block["type"] == "part" else block
        with self.path(disk["name"]).open("rb") as stream:
            mbr = stream.read(512)
        need(len(mbr) == 512 and mbr[510:] == b"\x55\xaa" and b"GRUB" in mbr[:0x1b8],
             disk["name"] + ": its MBR does not hold GRUB's boot sector; L4H boots through BIOS GRUB")
        tool = "grub2-editenv" if grubdir.endswith("grub2") else "grub-editenv"
        env = grub_env(self.run(tool, grubdir + "/grubenv", "list"))
        return dict(grubdir=grubdir, grub_tool=tool, grub_env=env, boot_uuid=block["uuid"],
                    boot_fstype=mount["fstype"],
                    grub_dir="/" + str(BIOS_DIR.relative_to(mount["target"])))

    def network(self):
        # Each physical NIC gets its own switch and a dom0 vNIC with its MAC.
        # The initramfs uses those MACs to restore names independent of ordering.
        # Software interfaces have no backing device in sysfs. Their names,
        # types and count are irrelevant to host uplink selection; the
        # existing userspace recreates them in dom0.
        links = json.loads(self.run("ip", "-json", "link", "show"))
        links = [link for link in links if self.path("/sys/class/net/" + link["ifname"] + "/device").exists()]
        need(1 <= len(links) <= 2,
             "automatic migration requires one or two physical NICs")
        uplinks = []
        for link in links:
            name = link["ifname"]
            need(re.fullmatch(r"[A-Za-z0-9_-]{1,15}", name), "unsupported interface name: " + name)
            base = "/sys/class/net/" + name
            need(link.get("link_type") == "ether" and "master" not in link and
                 not link.get("linkinfo", {}).get("info_kind") and not self.path(base + "/wireless").exists(),
                 name + ": need a plain Ethernet uplink (no wireless or master device)")
            pci = self.pci(base + "/device")
            vendor, device = pci["vendor"], pci["device"]
            mem = lambda bar: pci["bars"][bar][0] > 0 and not pci["bars"][bar][1]
            supported = (
                vendor == 0x1AF4 and device in (0x1000, 0x1041) and pci["msix"] >= 1
                and (pci["modern"] or device == 0x1000 and pci["legacy"]) or
                vendor == 0x1AE0 and device == 0x0042 and mem(0) and mem(2) and pci["msix"] >= 3 or
                vendor == 0x8086 and device in (0x1563, 0x15D1) and mem(0) and pci["msix"] >= 2 or
                vendor == 0x1D0F and device in (0x0EC2, 0x1EC2, 0xEC20, 0xEC21, 0x0051) and mem(0) and pci["msix"] >= 2)
            need(supported, name + ": supported uplinks are virtio-net, gVNIC, ENA and Intel X550")
            need(self.read(base + "/addr_assign_type") == "0",
                 name + ": uplink MAC has been changed; restore its permanent MAC first")
            mac = self.read(base + "/address").lower()
            need(re.fullmatch(r"(?:[0-9a-f]{2}:){5}[0-9a-f]{2}", mac) and
                 mac != "00:00:00:00:00:00" and not int(mac[:2], 16) & 1,
                 name + ": invalid Ethernet MAC")
            need(not any(n["mac"] == mac or n["bdf"] == pci["bdf"] for n in uplinks),
                 "uplinks need distinct MAC addresses and PCI devices")
            uplinks.append(dict(ifname=name, bdf=pci["bdf"], mac=mac))
        return sorted(uplinks, key=lambda n: n["bdf"])

    def check(self):
        if self.path(STATE).exists():
            return self.update()
        need(not self.path("/sys/kernel/l4h").exists(),
             "dom0 updates require an existing installer-managed installation; install from native Linux first")
        variant, memory, vcpus = self.hardware()
        plan = self.storage()
        uplinks = self.network()
        # Dom0 has 16 device slots shared by disks and vNICs. Count all disks
        # L4H could attach, not just fstab entries, so none are silently omitted.
        max_disks = 16 - len(uplinks)
        need(sum(b["type"] == "disk" for b in self.blocks.values()) <= max_disks,
             "automatic installation supports at most {} disks with {} uplink(s)".format(max_disks, len(uplinks)))
        need(self.read("/proc/1/comm") == "systemd", "automatic migration currently requires systemd as PID 1")
        if self.run("systemctl", "get-default") == "graphical.target":
            # Debian cloud images use graphical.target even without a display
            # manager. Reject a real graphical login, not the target's name.
            need(self.run("systemctl", "show", "--property=LoadState", "--value", "display-manager.service")
                 in ("not-found", "masked"),
                 "L4H has no native GPU/USB console; configure a headless system first")
        apparmor = self.path("/sys/kernel/security/apparmor/profiles")
        need(not apparmor.exists() or not apparmor.read_text().strip(),
             "the shipped kernel has no AppArmor; active profiles cannot be preserved")
        need(not list(self.path("/var/lib/dkms").glob("*/[0-9]*")),
             "DKMS modules cannot be reused with L4H's paravirtual kernel")
        selinux = self.path("/sys/fs/selinux/enforce")
        lsm = ""
        if selinux.exists():
            mode = selinux.read_text().strip()
            need(mode in ("0", "1"), "cannot read SELinux mode")
            lsm = " lsm=selinux enforcing=" + mode
        plan.update(variant=variant, memory=memory, vcpus=vcpus, uplinks=uplinks,
                    dom0_disks=max_disks, lsm=lsm)
        plan.update(self.efi_boot(plan) if plan["firmware"] == "uefi" else self.grub_boot(plan))
        return plan

    def update(self):
        """Update an existing deployment without reinterpreting dom0 as its host."""
        need(platform.system() == "Linux" and platform.machine() == "x86_64",
             "only x86_64 Linux is supported")
        safe_path(self.path(STATE))
        saved = json.loads(self.read(STATE))
        need(isinstance(saved, dict) and saved.get("version", 1) in (1, 2), "unsupported installation record")
        dom0 = self.path("/sys/class/misc/l4hctl/dev").is_file()
        need(dom0 or not self.path("/sys/kernel/l4h").exists(), "updates must run from dom0 or native Linux")
        firmware = saved.get("firmware", "uefi")
        need(firmware in ("uefi", "bios"), "invalid installed firmware type")
        need(dom0 or firmware == self.firmware(), "boot native Linux in the installation's firmware mode")
        data = json.loads(self.run("lsblk", "--json", "--list", "--paths", "--output",
                                  "NAME,TYPE,PKNAME,FSTYPE,UUID,PARTUUID,LABEL,PARTLABEL,PARTTYPE,PTTYPE,MAJ:MIN"))
        self.blocks = {b["name"]: b for b in data["blockdevices"]}
        root = self.mount("/")
        blocks = [b for b in self.blocks.values() if b["maj:min"] == root["maj:min"]]
        need(len(blocks) == 1 and blocks[0]["type"] in ("disk", "part") and
             root["fstype"] in ("ext4", "xfs") and "rw" in root["options"].split(","),
             "root must be a writable plain ext4 or XFS disk/partition")
        root_uuid = blocks[0].get("uuid")
        need(root_uuid and re.fullmatch(r"[a-fA-F0-9-]+", root_uuid), "root needs a filesystem UUID")
        need(saved.get("root_uuid", root_uuid) == root_uuid, "root filesystem differs from the installed root")
        plan = dict(update=True, dom0=dom0, firmware=firmware, root_uuid=root_uuid, root_type=root["fstype"])
        if firmware == "uefi":
            need(isinstance(saved.get("esp"), str) and saved["esp"].startswith("/"), "invalid installed ESP path")
            plan.update(self.esp(physical=False, target=saved["esp"]))
            need(plan["esp"] == saved["esp"] and
                 saved.get("esp_partuuid", plan["esp_partuuid"]) == plan["esp_partuuid"],
                 "existing L4H install is on a different ESP")
            need(isinstance(saved.get("entry"), str) and re.fullmatch(r"[0-9A-F]{4}", saved["entry"]),
                 "invalid installed EFI boot entry")
            plan["entry"] = saved["entry"]
            plan["previous_entry"] = saved["entry"]
            if dom0:
                need(not self.args.make_default, "UEFI boot order changes require native Linux; omit --make-default to update files")
                plan["boot"] = None  # seL4 does not expose EFI runtime services.
            else:
                plan["boot"] = boot_state(self.run("efibootmgr", "--verbose"))
                # NVRAM can lose or renumber entries independently of the
                # installed files. Reuse a matching entry, or let commit()
                # create one after validating the existing deployment below.
                plan["entry"] = l4h_entry(plan["boot"], plan, saved["entry"])
            directory = Path(plan["esp"]) / "l4h"
            payload = Path(plan["esp"]) / "EFI/L4H/l4h.efi"
        else:
            plan.update(self.grub(physical=False))
            need(saved.get("grubdir") == plan["grubdir"] and
                 saved.get("boot_uuid", plan["boot_uuid"]) == plan["boot_uuid"],
                 "existing L4H install uses a different boot configuration")
            custom = self.path(plan["grubdir"] + "/custom.cfg")
            safe_path(custom)
            if custom.exists():
                plan["grub_custom"] = custom.read_text()
                need(plan["grub_custom"].startswith(GENERATED), "L4H GRUB entry is unmanaged")
                need("--fs-uuid --set=root " + plan["boot_uuid"] + "\n" in plan["grub_custom"],
                     "L4H GRUB entry points to a different /boot filesystem")
            plan["default"] = bool(saved.get("default"))
            directory, payload = BIOS_DIR, BIOS_DIR / "bios/kernel.elf"
        config = directory / "l4h.conf"
        safe_path(self.path(config))
        need(self.path(config).is_file(), "installed l4h.conf is missing")
        original = text = self.path(config).read_text()
        cmdline = shlex.split(config_value(text, "dom0_cmdline"))
        need([arg for arg in cmdline if arg.startswith("root=")] == ["root=UUID=" + root_uuid],
             "installed dom0 root differs from the mounted root")
        safe_path(self.path(payload))
        variant = self.args.variant or saved.get("variant")
        if variant is None:
            need(self.path(payload).is_file(), "installed boot payload is missing and its variant was not recorded; specify --variant")
            key = (saved.get("release"), firmware, digest(self.path(payload)))
            if key not in self.variants:
                self.variants[key] = installed_variant(*key)
            variant = self.variants[key]
        need(variant in KERNEL_VARIANTS, "invalid installed kernel variant")
        if dom0:
            # Dom0's CPU view cannot establish whether the host can safely
            # drop SKIM or enable PCID. Same-variant updates and transitions
            # to variants with fewer requirements are safe.
            if self.args.variant:
                old = saved.get("variant")
                need(variant == old or variant == "skim-xapic-nopcid" or
                     old == "generic" and variant == "xapic-nopcid",
                     "changing to this kernel variant requires native Linux to check host CPU features")
        else:
            self.cpu_variant(variant)
        plan["variant"] = variant
        # Explicit overrides use host capacity, never dom0's allocated RAM/CPUs.
        if self.args.memory is not None or self.args.vcpus is not None:
            if dom0:
                info = self.run("/usr/local/bin/l4hctl", "info")
                ram = re.search(r"^memory:.* of (\d+) MiB$", info, re.M)
                cores = re.search(r"^cores:\s+(\d+)$", info, re.M)
                need(ram and cores, "cannot read host capacity from l4hctl info")
                total, cpus = int(ram[1]), int(cores[1])
            else:
                total = int(re.search(r"^MemTotal:\s+(\d+)", self.read("/proc/meminfo"), re.M)[1]) // 1024
                cpus = len(re.findall(r"^processor\s*:", self.read("/proc/cpuinfo"), re.M))
            if self.args.memory is not None:
                text = config_replace(text, "dom0_mem_mb", memory_size(total, self.args.memory))
            if self.args.vcpus is not None:
                need(1 <= self.args.vcpus <= min(cpus, 64), "dom0 vCPUs must fit the available CPUs (maximum 64)")
                text = config_replace(text, "dom0_vcpus", self.args.vcpus)
        plan["configuration"] = text
        plan["config_changed"] = text != original
        plan["config_mode"] = self.path(config).stat().st_mode & 0o777
        tracked = [STATE, config, payload]
        if firmware == "bios":
            tracked.append(Path(plan["grubdir"]) / "custom.cfg")
        plan["snapshot"] = {str(p): digest(self.path(p)) if self.path(p).is_file() else None for p in tracked}
        return plan

    def efi_boot(self, plan):
        boot = boot_state(self.run("efibootmgr", "--verbose"))
        existing = l4h_entry(boot)
        need(boot["current"] in boot["entries"] and boot["current"] != existing and
             boot["current"] in boot["order"].split(",") and boot["current"] in boot["active"],
             "run this installer from native Linux with its boot entry in BootOrder")
        need(boot["next"] is None or boot["next"] == existing,
             "BootNext is already scheduled for another entry; clear it before installing")
        if existing:
            need(owns_entry(boot, existing, plan), "existing L4H boot entry points to a different ESP")
            need(self.path(STATE).is_file(), "existing L4H boot entry is not managed by this installer")
            saved = json.loads(self.path(STATE).read_text())
            need(saved.get("esp") == plan["esp"] and saved.get("entry") == existing,
                 "existing L4H install is on a different ESP or boot entry")
        else:
            need(not self.path(STATE).exists() and not self.path(plan["esp"] + "/l4h").exists() and
                 not self.path(plan["esp"] + "/EFI/L4H").exists(),
                 "unmanaged L4H files exist; preserve or remove them before installing")
        return dict(boot=boot, entry=existing)

    def grub_boot(self, plan):
        custom = self.path(plan["grubdir"] + "/custom.cfg")
        saved = json.loads(self.path(STATE).read_text()) if self.path(STATE).is_file() else None
        if custom.exists():
            need(custom.is_file() and custom.read_text(errors="replace").startswith(GENERATED),
                 plan["grubdir"] + "/custom.cfg exists; merge or remove it before installing")
            need(saved is not None, "existing L4H GRUB entry is not managed by this installer")
            need(saved.get("firmware") == "bios" and saved.get("grubdir") == plan["grubdir"],
                 "existing L4H install uses a different boot configuration")
        else:
            need(saved is None and not self.path(BIOS_DIR).exists(),
                 "unmanaged L4H files exist; preserve or remove them before installing")
        # GRUB consumes next_entry by saving it empty.
        need(plan["grub_env"].get("next_entry") in (None, "", GRUB_ENTRY),
             "GRUB next_entry is already set for another entry; clear it before installing")
        return dict(default=bool(saved and saved.get("default")))


def configuration(plan):
    if plan.get("update"):
        return plan["configuration"]
    nic_config = "".join("{}={}\n".format(key, nic["bdf"]) for key, nic in
                         zip(("uplink_nic", "uplink2_nic"), plan["uplinks"]))
    net_cmdline = " ".join("l4h.net={mac},{ifname}".format(**nic) for nic in plan["uplinks"])
    # dom0_nics counts only switch 0's ports; uplink2_nic adds switch 1's vNIC.
    return ("# Generated by the L4H Linux installer.\n"
            "dom0_mem_mb={memory}\ndom0_vcpus={vcpus}\ndom0_io_pool_mb=0\n"
            "dom0_disks={dom0_disks}\ndom0_nics=1\nboot_disk={boot_disk}\n{nic_config}"
            'dom0_cmdline="console=hvc0 root=UUID={root_uuid} rootfstype={root_type} '
            'ro net.ifnames=0 {net_cmdline}{lsm}"\n').format(**plan, nic_config=nic_config, net_cmdline=net_cmdline)


def verify_efi(path):
    with path.open("rb") as stream:
        header = stream.read(64)
        need(len(header) == 64 and header[:2] == b"MZ", "release is not a PE executable")
        stream.seek(struct.unpack_from("<I", header, 60)[0])
        pe = stream.read(94)
    need(len(pe) == 94 and pe[:6] == b"PE\0\0\x64\x86" and pe[24:26] == b"\x0b\x02"
         and struct.unpack_from("<H", pe, 92)[0] == 10, "release is not an x86_64 EFI application")


def verify_elf(path, multiboot2=False):
    with path.open("rb") as stream:
        header = stream.read(32768)
    need(len(header) >= 64 and header[:6] == b"\x7fELF\x02\x01" and struct.unpack_from("<H", header, 18)[0] == 0x3E,
         path.name + " is not an x86_64 ELF file")
    # The multiboot2 header is 8-byte aligned in the first 32 KiB.
    need(not multiboot2 or any(struct.unpack_from("<I", header, offset)[0] == 0xE85250D6
                               for offset in range(0, len(header) - 3, 8)),
         path.name + " has no multiboot2 header")


def release_file(args, name, dest):
    sums = [line.split() for line in args.checksums.read_text().splitlines()]
    hashes = [line[0] for line in sums if len(line) == 2 and line[1] == name]
    need(len(hashes) == 1 and re.fullmatch(r"[a-f0-9]{64}", hashes[0]), "missing/duplicate checksum for " + name)
    run("curl", "--fail", "--silent", "--show-error", "--location", "--proto", "=https",
        "--proto-redir", "=https", "--retry", "3", "--output", str(dest),
        "https://github.com/losfair/l4h/releases/download/" + args.release + "/" + name)
    need(digest(dest) == hashes[0], name + ": download checksum mismatch")


def download_efi(args, plan, dest):
    release_file(args, "l4h-" + plan["variant"] + ".efi", dest)
    verify_efi(dest)


BIOS_FILES = ("grub.cfg", "l4h-root.elf", "vmlinux", "kmods.erofs")


def unpack_bios(archive, work, variant):
    """Unpack l4h-bios-x86_64.tar.xz's regular files into work; return its directory."""
    with tarfile.open(archive, "r:xz") as tar:
        for item in tar:
            path = PurePosixPath(item.name)
            need(not path.is_absolute() and ".." not in path.parts and 1 <= len(path.parts) <= 2
                 and path.parts[0] == BIOS_PACKAGE and (item.isfile() or item.isdir()),
                 "unsafe BIOS package member: " + item.name)
            if item.isfile():
                dest = work / path
                dest.parent.mkdir(exist_ok=True)
                with tar.extractfile(item) as src, dest.open("xb") as out:
                    shutil.copyfileobj(src, out)
    bios = work / BIOS_PACKAGE
    kernel = "kernel-" + variant + ".elf"
    for name in BIOS_FILES + (kernel,):
        need((bios / name).is_file() and (bios / name).stat().st_size > 0, "BIOS package lacks " + name)
    verify_elf(bios / kernel, multiboot2=True)
    verify_elf(bios / "l4h-root.elf")
    verify_elf(bios / "vmlinux")
    return bios


def download_bios(args, plan, work):
    archive = work / (BIOS_PACKAGE + ".tar.xz")
    release_file(args, archive.name, archive)
    return unpack_bios(archive, work, plan["variant"])


def installed_variant(release, firmware, installed_hash):
    """Older installation records omitted the variant. Match their boot file
    to the recorded release rather than guessing from dom0's virtual CPU."""
    need(isinstance(release, str) and re.fullmatch(r"v[A-Za-z0-9][A-Za-z0-9._-]*", release),
         "cannot identify the installed variant; specify --variant")
    with tempfile.TemporaryDirectory() as work:
        work = Path(work)
        sums = work / "SHA256SUMS"
        try:
            run("curl", "--fail", "--silent", "--show-error", "--location", "--proto", "=https",
                "--proto-redir", "=https", "--retry", "3", "--output", str(sums),
                "https://github.com/losfair/l4h/releases/download/" + release + "/SHA256SUMS")
            variants = KERNEL_VARIANTS
            if firmware == "uefi":
                lines = [line.split() for line in sums.read_text().splitlines()]
                matches = [v for v in variants if
                           [p[0] for p in lines if len(p) == 2 and p[1] == "l4h-" + v + ".efi"] == [installed_hash]]
            else:
                archive = work / (BIOS_PACKAGE + ".tar.xz")
                release_file(argparse.Namespace(release=release, checksums=sums), archive.name, archive)
                matches = []
                with tarfile.open(archive, "r:xz") as tar:
                    for variant in variants:
                        members = [m for m in tar.getmembers()
                                   if m.name == BIOS_PACKAGE + "/kernel-" + variant + ".elf"]
                        if len(members) != 1 or not members[0].isfile():
                            continue
                        value = hashlib.sha256()
                        with tar.extractfile(members[0]) as stream:
                            for block in iter(lambda: stream.read(1024 * 1024), b""):
                                value.update(block)
                        if value.hexdigest() == installed_hash:
                            matches.append(variant)
            need(len(matches) == 1, "installed boot file does not match a unique release variant")
            return matches[0]
        except (Incompatible, OSError, tarfile.TarError) as error:
            raise Incompatible("cannot identify the installed variant; specify --variant: " + str(error)) from error


def safe_path(path):
    for part in (path, *path.parents):
        need(not part.is_symlink(), "refusing symlink in install path: " + str(part))
    need(not path.exists() or path.is_file(), "not a regular file: " + str(path))


def atomic_copy(source, dest, mode=0o644):
    safe_path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=".l4h-", dir=dest.parent)
    try:
        with os.fdopen(fd, "wb") as out, source.open("rb") as stream:
            shutil.copyfileobj(stream, out)
            out.flush()
            os.fsync(out.fileno())
        os.chmod(name, mode)
        os.replace(name, dest)
    finally:
        Path(name).unlink(missing_ok=True)


class EfiBoot:
    """The L4H application on the ESP, selected through a firmware boot entry."""

    def __init__(self, plan, efi, make_default, command):
        self.plan, self.efi, self.make_default, self.command = plan, efi, make_default, command
        entries = plan["boot"]["entries"] if plan["boot"] else {}
        previous = plan.get("previous_entry")
        self.entry = (plan["entry"] or (previous if previous not in entries else None) or
                      next(("%04X" % n for n in range(65536) if "%04X" % n not in entries), None))
        need(self.entry is not None, "no free EFI boot entry")
        self.fs, self.space = Path(plan["esp"]), "the ESP"
        self.l4h = self.fs / "l4h"
        self.saved, self.selected, self.activated = plan["boot"], False, False
        pending = self.saved["next"] if self.saved else None
        self.foreign_next = (pending is not None and not owns_entry(self.saved, pending, plan) and
                             not (pending == previous and pending not in entries))

    def files(self):
        return [(self.efi, self.fs / "EFI/L4H/l4h.efi", 0o644)]

    def selection(self, temp):
        return []

    def state(self):
        return dict(esp=self.plan["esp"], esp_partuuid=self.plan["esp_partuuid"], entry=self.entry)

    def unchanged(self):
        # Re-read immediately before publishing in case another boot tool ran.
        if self.plan["boot"] is None:
            return
        need(boot_state(self.command("efibootmgr", "--verbose")) == self.plan["boot"],
             "EFI boot state changed during installation; rerun the installer")

    def select(self):
        plan, entry, command = self.plan, self.entry, self.command
        if plan["boot"] is None:
            return
        if plan["entry"] is None:
            self.selected = True
            command("efibootmgr", "--create-only", "--bootnum", entry, "--disk", plan["esp_disk"],
                    "--part", plan["esp_part"], "--label", "L4H", "--loader", LOADER)
        current = boot_state(command("efibootmgr", "--verbose"))
        need(owns_entry(current, entry, plan) and current["order"] == plan["boot"]["order"],
             "firmware did not create the L4H entry without changing BootOrder")
        if entry not in current["active"]:
            self.selected = True
            self.activated = True
            command("efibootmgr", "--bootnum", entry, "--active")
        order = ",".join([entry] + [n for n in plan["boot"]["order"].split(",") if n != entry])
        pending = plan["boot"]["next"]
        if self.make_default:
            self.selected = True
            command("efibootmgr", "--bootorder", order)
        if not self.foreign_next and (not self.make_default or
                                     pending is not None and pending not in plan["boot"]["entries"]):
            self.selected = True
            command("efibootmgr", "--bootnext", entry)
            pending = entry
        self.final = boot_state(command("efibootmgr", "--verbose"))
        need(self.final["order"] == (order if self.make_default else plan["boot"]["order"]) and
             self.final["next"] == pending and entry in self.final["active"],
             "firmware did not retain the requested boot settings")

    def undo(self, failures):
        if not self.selected:
            return
        plan, entry, command = self.plan, self.entry, self.command
        commands = []
        if plan["entry"] is None:
            # Creation can fail because a different boot tool took the
            # chosen number. Never remove that tool's unrelated entry.
            try:
                if owns_entry(boot_state(command("efibootmgr", "--verbose")), entry, plan):
                    commands.append(("efibootmgr", "--bootnum", entry, "--delete-bootnum"))
            except Exception as error:
                failures.append("cannot determine whether entry was created: " + str(error))
        elif self.activated:
            commands.append(("efibootmgr", "--bootnum", entry, "--inactive"))
        commands.append(("efibootmgr", "--bootorder", plan["boot"]["order"]))
        commands.append(("efibootmgr", "--bootnext", plan["boot"]["next"]) if plan["boot"]["next"]
                        else ("efibootmgr", "--delete-bootnext"))
        for cmd in commands:
            try:
                command(*cmd)
            except Exception as error:
                failures.append(str(error))

    def report(self, release, backup):
        print("Installed {} as Boot{}. Backup: {}".format(release, self.entry, backup))
        if self.plan["boot"] is None:
            print("UEFI boot selection is unchanged: dom0 cannot access firmware variables. "
                  "Select L4H in firmware if it is not already the default.")
            return
        print("BootOrder: " + self.final["order"])
        if self.final["order"].split(",")[0] == self.entry:
            print("L4H is the default boot entry.")
        if self.foreign_next:
            print("Preserved BootNext={} for the previously scheduled boot; L4H's files are updated.".format(self.final["next"]))
        elif not self.make_default:
            print("L4H is selected for the next boot; the existing BootOrder is preserved.")


class GrubBoot:
    """tools/mkbios.sh's files in /boot/l4h, booted from a custom.cfg entry in
    the distribution's BIOS GRUB and selected once through next_entry."""

    def __init__(self, plan, bios, make_default, command):
        self.plan, self.bios, self.command = plan, bios, command
        # Like BootOrder on UEFI, an earlier --make-default stays.
        self.default = make_default or plan["default"]
        self.fs, self.space, self.l4h = BIOS_DIR.parent, "/boot", BIOS_DIR
        self.env = plan["grubdir"] + "/grubenv"
        self.saved, self.selected = plan["grub_env"], False
        self.foreign_next = self.saved.get("next_entry") not in (None, "", GRUB_ENTRY)

    def files(self):
        bios = self.l4h / "bios"
        return ([(self.bios / ("kernel-" + self.plan["variant"] + ".elf"), bios / "kernel.elf", 0o644)] +
                [(self.bios / name, bios / name, 0o644) for name in BIOS_FILES])

    def selection(self, temp):
        # Published after the files it boots; GRUB lists it from then on.
        text = self.plan.get("grub_custom")
        if text is not None:
            if self.default == self.plan["default"]:
                return []
            text = text.rstrip("\n") + '\nif [ -z "$boot_once" ]; then set default=l4h; fi\n'
        else:
            text = grub_entry(self.plan, self.default)
        custom = temp / "custom.cfg"
        custom.write_text(text)
        return [(custom, Path(self.plan["grubdir"]) / "custom.cfg", 0o644)]

    def state(self):
        return dict(grubdir=self.plan["grubdir"], boot_uuid=self.plan["boot_uuid"], default=self.default)

    def current(self):
        return grub_env(self.command(self.plan["grub_tool"], self.env, "list"))

    def unchanged(self):
        need(self.current() == self.plan["grub_env"], "GRUB environment changed during installation; rerun the installer")

    def select(self):
        before = self.plan["grub_env"].get("next_entry")
        if not self.default and not self.foreign_next:
            self.selected = True
            self.command(self.plan["grub_tool"], self.env, "set", "next_entry=" + GRUB_ENTRY)
        need(self.current().get("next_entry") == (before if self.default or self.foreign_next else GRUB_ENTRY),
             "GRUB did not retain the requested boot settings")

    def undo(self, failures):
        if not self.selected:
            return
        before = self.plan["grub_env"].get("next_entry")
        try:
            self.command(self.plan["grub_tool"], self.env,
                         *(("set", "next_entry=" + before) if before else ("unset", "next_entry")))
        except Exception as error:
            failures.append(str(error))

    def report(self, release, backup):
        print("Installed {} as the GRUB entry L4H ({}/custom.cfg). Backup: {}".format(
            release, self.plan["grubdir"], backup))
        if self.default:
            print("L4H is the default GRUB entry.")
        if self.foreign_next:
            print("Preserved GRUB next_entry={} for the previously scheduled boot; L4H's files are updated.".format(self.saved["next_entry"]))
        elif not self.default:
            print("L4H is selected for the next boot only (GRUB next_entry); the native default is preserved.")


def commit(plan, package, payload, release, make_default, root=Path("/"), command=run):
    """Back up every destination, publish files, then select L4H for boot; undo on failure.

    payload is the UEFI application, or the unpacked BIOS package."""
    path = lambda name: root / str(name).lstrip("/")
    for name, checksum in plan.get("snapshot", {}).items():
        safe_path(path(name))
        need((digest(path(name)) if path(name).is_file() else None) == checksum,
             "installed files changed during update; rerun the installer")
    boot = (EfiBoot if plan["firmware"] == "uefi" else GrubBoot)(plan, payload, make_default, command)
    with tempfile.TemporaryDirectory() as temp:
        temp = Path(temp)
        config = temp / "l4h.conf"
        config.write_text(configuration(plan))
        state = temp / "install.json"
        record = dict(version=2, firmware=plan["firmware"], variant=plan["variant"],
                      root_uuid=plan["root_uuid"], release=release, **boot.state())
        state.write_text(json.dumps(record, indent=2) + "\n")
        configs = ([(config, boot.l4h / "l4h.conf", plan.get("config_mode", 0o644))]
                   if not plan.get("update") or plan["config_changed"] else [])
        files = (boot.files() +
                 [(package / "install/initrd", boot.l4h / "dom0/initrd", 0o644),
                  (package / "bin/l4hctl", Path("/usr/local/bin/l4hctl"), 0o755),
                  (package / "share/licenses/l4hctl/LICENSE", Path("/usr/local/share/licenses/l4hctl/LICENSE"), 0o644)] +
                 configs + boot.selection(temp) + [(state, STATE, 0o600)])
        for source, target, _ in files:
            need(source.is_file() and source.stat().st_size > 0, "release file missing/empty: " + str(source))
            safe_path(path(target))
        missing_dirs = {parent for _, target, _ in files for parent in path(target).parents
                        if not parent.exists()}
        need(shutil.disk_usage(path(boot.fs)).free > sum(s.stat().st_size for s, t, _ in files if t.is_relative_to(boot.fs)) + 16 * 1024**2,
             "not enough free space on {} (payload plus 16 MiB required)".format(boot.space))
        # A private persistent backup permits recovery even if rollback itself
        # fails (e.g. the firmware refuses further writes or the disk fills).
        backup_base = path("/var/lib/l4h/backups")
        safe_path(backup_base / "placeholder")
        backup_base.mkdir(parents=True, exist_ok=True, mode=0o700)
        backup = Path(tempfile.mkdtemp(prefix=datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ-"), dir=backup_base))
        manifest = []
        for _, target, _ in files:
            dest = path(target)
            saved = backup / str(len(manifest))
            if dest.exists():
                shutil.copy2(dest, saved)
            manifest.append(dict(path=str(target), saved=saved.name if dest.exists() else None,
                                 mode=dest.stat().st_mode & 0o777 if dest.exists() else 0o644))
        (backup / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
        (backup / "boot.json").write_text(json.dumps(boot.saved, indent=2) + "\n")
        os.sync()
        changed = []
        try:
            boot.unchanged()
            for index, (source, target, mode) in enumerate(files):
                if target == STATE:
                    continue
                changed.append(index)
                atomic_copy(source, path(target), mode)
            os.sync()
            boot.select()
            changed.append(len(files) - 1)
            atomic_copy(state, path(STATE), 0o600)
            os.sync()
        except BaseException:
            failures = []
            boot.undo(failures)
            for index in reversed(changed):
                item = manifest[index]
                try:
                    if item["saved"]:
                        atomic_copy(backup / item["saved"], path(item["path"]), item["mode"])
                    else:
                        path(item["path"]).unlink(missing_ok=True)
                except Exception as error:
                    failures.append(str(error))
            for directory in sorted(missing_dirs, key=lambda p: len(p.parts), reverse=True):
                try:
                    directory.rmdir()
                except OSError:
                    pass  # Keep backup directories and anything another tool created.
            os.sync()
            print("l4h: installation failed; backup: " + str(backup), file=sys.stderr)
            if failures:
                print("l4h: rollback incomplete: " + "; ".join(failures), file=sys.stderr)
            raise
    boot.report(release, backup)
    if plan.get("dom0"):
        print("Run /usr/local/bin/l4hctl host-reboot when ready to reboot the host. "
              "A normal reboot only restarts dom0; no reboot was performed.")
    else:
        print("Reboot when ready; no reboot was performed.")


def arguments(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--release")
    parser.add_argument("--checksums", type=Path)
    parser.add_argument("--esp")
    parser.add_argument("--memory", type=int)
    parser.add_argument("--vcpus", type=int)
    parser.add_argument("--variant", choices=KERNEL_VARIANTS)
    parser.add_argument("--assume-stable-tsc", action="store_true",
                        help="allow missing constant_tsc for experimental installs; assume TSC stability without verifying it")
    parser.add_argument("--make-default", action="store_true")
    return parser.parse_args(argv)


def main():
    args = arguments()
    need(os.geteuid() == 0, "run as root to read PCI configuration, disks and EFI variables")
    package = Path(__file__).resolve().parent.parent
    preflight = Preflight(args)
    plan = preflight.check()
    boot = plan["esp"] if plan["firmware"] == "uefi" else "BIOS GRUB " + plan["grubdir"]
    if plan.get("update"):
        print("Update: {} on {}, root UUID={} (from {})".format(
            plan["variant"], boot, plan["root_uuid"], "dom0" if plan["dom0"] else "native Linux"))
        print("Preserving l4h.conf" + (" with the requested resource overrides." if plan["config_changed"] else "."))
    else:
        print("Compatible: {} on {}, root UUID={}, dom0 {} MiB / {} CPUs".format(
            plan["variant"], boot, plan["root_uuid"], plan["memory"], plan["vcpus"]))
        for switch, nic in enumerate(plan["uplinks"]):
            print("  Switch {}: uplink {} (PCI {}, MAC {})".format(switch, nic["ifname"], nic["bdf"], nic["mac"]))
        print("Firmware behavior and application compatibility still require a boot test.")
    if args.check:
        return
    need(args.release and re.fullmatch(r"v[A-Za-z0-9][A-Za-z0-9._-]*", args.release) and args.checksums,
         "install through tools/install.sh with a verified release package")
    with tempfile.TemporaryDirectory() as work:
        if plan["firmware"] == "uefi":
            payload = Path(work) / "l4h.efi"
            download_efi(args, plan, payload)
        else:
            payload = download_bios(args, plan, Path(work))
        # Serialize installers, then repeat preflight before any persistent write.
        with open("/run/l4h-install.lock", "w") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            need(preflight.check() == plan, "system changed during download; rerun the installer")
            commit(plan, package, payload, args.release, args.make_default)


if __name__ == "__main__":
    try:
        main()
    except (Incompatible, OSError, ValueError, KeyError, tarfile.TarError) as error:
        sys.exit("l4h: " + str(error))
