#!/usr/bin/env python3
"""Preflight and transactional installation; normally invoked by tools/install.sh.

Only the standard library is needed. Probes are read-only; all persistent writes
live in commit(). Keep the device predicates in sync with blkd.rs and netd.rs.

UEFI machines boot the L4H application from the ESP through an NVRAM entry.
BIOS machines boot tools/mkbios.sh's files in /boot/l4h from a menu entry in
the distribution's GRUB (custom.cfg), selected once through GRUB's next_entry.
"""

